def _hit(code: str, pattern: str) -> bool:
    if "-" in pattern:
        lo, hi = pattern.split("-")
        return lo <= code.ljust(10, "0") <= hi
    return code.startswith(pattern)


class Excise:
    def __init__(self, data: dict):
        self.categories: list[dict] = data["categories"]
        self.edition: str = data.get("edition", "")
        self.fetched: str | None = data.get("fetched")

    def _rate(self, cat: dict, today: str) -> dict | None:
        for r in cat["rates"]:
            if (r["from"] or "") <= today and (r["to"] is None or today <= r["to"]):
                return r
        return None

    def excise(self, code: str, today: dt.date | None = None) -> dict | None:
        day = (today or dt.date.today()).isoformat()
        for patterns, names, condition in MAP:  # первая подходящая строка: 2208 9091 раньше 2208
            if not any(_hit(code, p) for p in patterns):
                continue
            items = []
            for cat in self.categories:
                if not cat["name"].startswith(names):
                    continue
                if cat["name"].startswith("этиловый спирт") and "ввозимый в Российскую" not in cat["name"]:
                    continue
                r = self._rate(cat, day)
                if r:
                    items.append({"kind": cat["name"], "rate": r["rate"], "from": r["from"], "to": r["to"]})
            if not items:
                return None
            return {"items": items, "condition": condition, "source": SOURCE, "edition": self.edition,
                    "as_of": self.fetched}
        return None


def load_from_env() -> Excise | None:
    path = os.environ.get("EXCISE_PATH", str(Path(__file__).parent / "data" / "excise.json"))
    if not path or not os.path.exists(path):
        return None
    with open(path, encoding="utf-8") as f:
        return Excise(json.load(f))
