class Conformity:
    def __init__(self, rows, period: str = ""):
        self.period = period
        self.by_code: dict[str, tuple[int, int, list[tuple[str, int]]]] = {}
        for row in rows:
            tr = []
            for part in (row["tr"] or "").split(" | "):
                name, _, k = part.rpartition("=")
                if name and k.isdigit():
                    tr.append((name, int(k)))
            self.by_code[row["code"]] = (int(row["n"]), int(row["n_cert"]), tr)

    def lookup(self, code: str) -> dict | None:
        """Что оформляли под кодом, а если документов мало — под ближайшим старшим узлом
        (8, 6, 4 знака); digits в ответе — по какому узлу посчитано."""
        for key in dict.fromkeys(code[:d] for d in (10, 8, 6, 4) if len(code) >= d):
            n, n_cert, tr = self.by_code.get(key, (0, 0, []))
            if n < MIN_DOCS:
                continue
            return {
                "code": key,
                "digits": len(key),
                "documents": n,
                "certificate_share": round(n_cert / n, 3),
                "regulations": [{"name": name, "number": NUMBERS.get(name), "share": round(k / n, 3)}
                                for name, k in tr if k / n >= MIN_SHARE],
                "source": "Реестры деклараций и сертификатов соответствия Росаккредитации (открытые данные)",
                "period": self.period,
                "note": "Что оформляли заявители под этим кодом, а не требование закона: "
                        "нужен ли документ и какой, решает регламент по виду товара.",
            }
        return None


def load(path: str | Path) -> Conformity:
    path = Path(path)
    opener = gzip.open if path.suffix == ".gz" else open
    with opener(path, "rt", encoding="utf-8", newline="") as f:
        first = f.readline()
        period = ""
        if first.startswith("#"):
            m = re.search(r"period:\s*(.+)", first)
            period = m.group(1).strip() if m else ""
        else:
            f.seek(0)
        reader = csv.DictReader(f, delimiter="\t")
        missing = [c for c in REQUIRED if c not in (reader.fieldnames or [])]
        if missing:
            raise ValueError(f"{path}: нет колонок {', '.join(missing)}")
        return Conformity(reader, period)


def load_from_env() -> Conformity | None:
    path = os.environ.get("CONFORMITY_PATH", "").strip()
    return load(path) if path else None
